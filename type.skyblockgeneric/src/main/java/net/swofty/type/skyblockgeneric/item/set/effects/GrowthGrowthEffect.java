import net.swofty.type.skyblockgeneric.item.set.impl.ArmorSetEffect;

import java.util.List;

public final class GrowthGrowthEffect extends ArmorSetEffect {
    @Override
    public String getName() { return "Growth"; }

    @Override
    public ArmorSetBonusType getType() { return ArmorSetBonusType.FULL_SET; }

    @Override
    public List<String> getDescription(ArmorSetContext context) {
        return List.of("Killing a mob regenerates <sbstat:vitality:5> and permanently adds <sbstat:health:+1> to each piece, up to +100.");
    }

}
